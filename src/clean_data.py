"""
数据清洗 + 特征工程
读取已合并去重的汇总数据，输出清洗后的数据（含全部衍生字段）
运行：python src/clean_data.py
"""
import pandas as pd
import os

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', '')

# ============ 读取已合并去重的数据 ============
df = pd.read_csv(DATA_DIR + 'b站热门数据_汇总.csv', encoding='utf-8-sig')
print('原始条数:', len(df))

# ============ 1. 字段类型转换 ============
# 发布时间是字符串 '2026-07-25 09:30:00'，转成日期时间格式
df['发布时间'] = pd.to_datetime(df['发布时间'])
# 数据日期是字符串 '20260726'，先转成 2026-07-26 这种格式，再转成日期
df['数据日期'] = pd.to_datetime(df['数据日期'], format='%Y%m%d')
# 数值列统一转成数值类型（防止文本混入）
num_cols = ['播放量', '点赞数', '评论数', '弹幕数', '收藏数', '投币数', '分享数', '时长秒']
for col in num_cols:
    df[col] = pd.to_numeric(df[col])

# ============ 2. 无效值剔除 ============
before = len(df)
df = df[df['播放量'] > 0]          # 播放量大于 0
df = df[df['时长秒'] > 0]          # 时长大于 0
df = df[df['发布时间'].notna()]    # 发布时间不是空
df = df[df['数据日期'].notna()]    # 数据日期不是空
print('剔除无效值:', before - len(df), '条')

# ============ 3. 异常值处理 ============
# 时长超过 10 小时(36000秒)的极端异常视频剔除
before = len(df)
df = df[df['时长秒'] <= 36000]
print('剔除超长视频(>10h):', before - len(df), '条')
print('剔除后条数:', len(df))

# ============ 4. 计算发布天数 ============
# 发布天数 = 数据日期 - 发布时间，单位天
df['发布天数'] = (df['数据日期'] - df['发布时间']).dt.days

# 发布天数小于等于 0 的样本：置为 1，并打标记
df['发布天数异常'] = df['发布天数'] <= 0
df.loc[df['发布天数异常'], '发布天数'] = 1
print('发布天数异常置 1 的条数:', df['发布天数异常'].sum())

# ============ 5. 计算互动率（消掉播放量量级影响） ============
df['点赞率'] = df['点赞数'] / df['播放量']
df['投币率'] = df['投币数'] / df['播放量']
df['收藏率'] = df['收藏数'] / df['播放量']
df['评论率'] = df['评论数'] / df['播放量']
df['弹幕率'] = df['弹幕数'] / df['播放量']
df['分享率'] = df['分享数'] / df['播放量']

# ============ 6. B站特色质量指标 ============
# 三连率 = (点赞 + 投币 + 收藏) / 播放量
df['三连率'] = (df['点赞数'] + df['投币数'] + df['收藏数']) / df['播放量']
# 币赞比 = 投币 / 点赞（投币门槛比点赞高，反映真实认可度）
df['币赞比'] = df['投币数'] / df['点赞数']

# ============ 7. 内容密度指标 ============
# 弹幕密度 = 弹幕数 / 时长秒，看单位时长内观众参与度
df['弹幕密度'] = df['弹幕数'] / df['时长秒']

# ============ 8. 样本分层标签（按播放量分位数） ============
q30 = df['播放量'].quantile(0.30)   # 30% 分位
q90 = df['播放量'].quantile(0.90)   # 90% 分位
q99 = df['播放量'].quantile(0.99)   # 99% 分位

def level(p):
    if p >= q99:
        return '超级爆款'
    if p >= q90:
        return '头部爆款'
    if p >= q30:
        return '腰部普通'
    return '尾部低播放'

df['播放分层'] = df['播放量'].apply(level)

print('分位点: q30=%d, q90=%d, q99=%d' % (q30, q90, q99))
print('分层统计:')
print(df['播放分层'].value_counts().to_string())

# ============ 保存清洗后的数据 ============
df.to_csv(DATA_DIR + 'b站数据_清洗后.csv', index=False, encoding='utf-8-sig')
print('已保存: b站数据_清洗后.csv')
