"""
数据清洗 + 特征工程
读取已合并去重的汇总数据，输出清洗后的数据（含全部衍生字段）
运行：python src/clean_data.py
"""
import pandas as pd
import os

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', '')

# ============ 读取已合并去重的数据 ============
df = pd.read_csv(DATA_DIR + 'b站热门数据_汇总.csv', encoding='utf-8-sig')
print('原始条数:', len(df))

# ============ 1. 字段类型转换 ============
# 发布时间是字符串 '2026-07-25 09:30:00'，转成日期时间格式
df['发布时间'] = pd.to_datetime(df['发布时间'])
# 数据日期是字符串 '20260726'，先转成 2026-07-26 这种格式，再转成日期
df['数据日期'] = pd.to_datetime(df['数据日期'], format='%Y%m%d')
# 数值列统一转成数值类型（防止文本混入）
num_cols = ['播放量', '点赞数', '评论数', '弹幕数', '收藏数', '投币数', '分享数', '时长秒']
for col in num_cols:
    df[col] = pd.to_numeric(df[col])

# ============ 2. 无效值剔除 ============
before = len(df)
df = df[df['播放量'] > 0]          # 播放量大于 0
df = df[df['时长秒'] > 0]          # 时长大于 0
df = df[df['发布时间'].notna()]    # 发布时间不是空
df = df[df['数据日期'].notna()]    # 数据日期不是空
print('剔除无效值:', before - len(df), '条')

# ============ 3. 异常值处理 ============
# 时长超过 10 小时(36000秒)的极端异常视频剔除
before = len(df)
df = df[df['时长秒'] <= 36000]
print('剔除超长视频(>10h):', before - len(df), '条')
print('剔除后条数:', len(df))

# ============ 4. 计算发布天数（精确到小时） ============
# 发布经过的完整小时数 = 数据日期 - 发布时间
df['发布小时'] = (df['数据日期'] - df['发布时间']).dt.total_seconds() / 3600
# 发布天数 = 小时数 / 24（精确小数，如 1.5 天、2.6 天）
df['发布天数'] = df['发布小时'] / 24
print('发布小时数范围:', round(df['发布小时'].min(), 1), '-', round(df['发布小时'].max(), 1))

# 发布时间晚于采集日0点（发布小时为负）的异常样本：仅保留发布时间在采集日之前的
before = len(df)
df = df[df['发布小时'] > 0]
print('剔除发布时间晚于采集日的异常:', before - len(df), '条')

# ============ 4.5 剔除不满 24 小时的新视频 ============
# 不满 24 小时视频播放累积不足，日均播放会被小分母高估，且爆款标签不可靠
# 仅保留"已发布满 1 天"的视频做分析（训练集），不满 24h 的视频另存供预测演示
before = len(df)
new_videos = df[df['发布小时'] < 24]
df = df[df['发布小时'] >= 24]
print('剔除不满24h的新视频:', len(new_videos), '条（保留满1日视频', len(df), '条）')

# ============ 5. 计算互动率（消掉播放量量级影响） ============
df['点赞率'] = df['点赞数'] / df['播放量']
df['投币率'] = df['投币数'] / df['播放量']
df['收藏率'] = df['收藏数'] / df['播放量']
df['评论率'] = df['评论数'] / df['播放量']
df['弹幕率'] = df['弹幕数'] / df['播放量']
df['分享率'] = df['分享数'] / df['播放量']

# ============ 6. B站特色质量指标 ============
# 三连率 = (点赞 + 投币 + 收藏) / 播放量
df['三连率'] = (df['点赞数'] + df['投币数'] + df['收藏数']) / df['播放量']
# 币赞比 = 投币 / 点赞（投币门槛比点赞高，反映真实认可度）
df['币赞比'] = df['投币数'] / df['点赞数']

# ============ 7. 内容密度指标 ============
# 弹幕密度 = 弹幕数 / 时长秒，看单位时长内观众参与度
df['弹幕密度'] = df['弹幕数'] / df['时长秒']

# ============ 8. 热度基准：日均播放量 ============
# 播放量受发布天数影响（老视频累积更多），用 播放量/发布天数 消除时效差异
# 发布天数用精确小数（小时数/24），避免整天天数导致的分母误差
df['日均播放'] = df['播放量'] / df['发布天数']

# ============ 9. 样本分层标签（按日均播放量分位数） ============
# 用日均播放而非原始播放量分层，避免"老视频天然接近爆款线"的偏差
q30 = df['日均播放'].quantile(0.30)   # 30% 分位
q90 = df['日均播放'].quantile(0.90)   # 90% 分位
q99 = df['日均播放'].quantile(0.99)   # 99% 分位

def level(p):
    if p >= q99:
        return '超级爆款'
    if p >= q90:
        return '头部爆款'
    if p >= q30:
        return '腰部普通'
    return '尾部低播放'

df['播放分层'] = df['日均播放'].apply(level)

print('分位点: q30=%d, q90=%d, q99=%d' % (q30, q90, q99))
print('分层统计:')
print(df['播放分层'].value_counts().to_string())

# ============ 保存清洗后的数据 ============
df.to_csv(DATA_DIR + 'b站数据_清洗后.csv', index=False, encoding='utf-8-sig')
# 不满24h的新视频另存（供预测演示）
if len(new_videos) > 0:
    new_videos.to_csv(DATA_DIR + 'b站数据_新视频.csv', index=False, encoding='utf-8-sig')
    print('已另存不满24h新视频: b站数据_新视频.csv（', len(new_videos), '条）')
print('已保存: b站数据_清洗后.csv')
